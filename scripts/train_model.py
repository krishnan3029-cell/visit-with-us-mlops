
"""Train, evaluate, track, and save the tourism purchase model."""

import json
from pathlib import Path

import joblib
import mlflow
import mlflow.sklearn
import pandas as pd

from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
)
from sklearn.model_selection import RandomizedSearchCV, StratifiedKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "artifacts" / "processed"
MODEL_DIR = ROOT / "models"
REPORT_DIR = ROOT / "reports"

MODEL_DIR.mkdir(parents=True, exist_ok=True)
REPORT_DIR.mkdir(parents=True, exist_ok=True)

# Load data generated by the preparation job
train_df = pd.read_csv(DATA_DIR / "train.csv")
test_df = pd.read_csv(DATA_DIR / "test.csv")

TARGET = "ProdTaken"

X_train = train_df.drop(columns=[TARGET])
y_train = train_df[TARGET].astype(int)

X_test = test_df.drop(columns=[TARGET])
y_test = test_df[TARGET].astype(int)

# Define preprocessing
numeric_cols = X_train.select_dtypes(
    include=["number"]
).columns.tolist()

categorical_cols = X_train.select_dtypes(
    include=["object", "category", "string"]
).columns.tolist()

preprocessor = ColumnTransformer(
    transformers=[
        (
            "numeric",
            SimpleImputer(strategy="median"),
            numeric_cols,
        ),
        (
            "categorical",
            Pipeline([
                ("imputer", SimpleImputer(strategy="most_frequent")),
                ("encoder", OneHotEncoder(handle_unknown="ignore")),
            ]),
            categorical_cols,
        ),
    ]
)

# Define model
pipeline = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", RandomForestClassifier(
        random_state=42,
        n_jobs=1,
    )),
])

# Hyperparameter tuning
params = {
    "classifier__n_estimators": [100, 200, 300],
    "classifier__max_depth": [None, 10, 20, 30],
    "classifier__min_samples_split": [2, 5, 10],
    "classifier__min_samples_leaf": [1, 2, 4],
    "classifier__max_features": ["sqrt", "log2"],
    "classifier__class_weight": [None, "balanced"],
}

search = RandomizedSearchCV(
    estimator=pipeline,
    param_distributions=params,
    n_iter=15,
    scoring="roc_auc",
    cv=StratifiedKFold(
        n_splits=5,
        shuffle=True,
        random_state=42,
    ),
    random_state=42,
    n_jobs=-1,
    verbose=1,
    refit=True,
)

# SQLite experiment tracking
mlflow.set_tracking_uri(
    f"sqlite:///{(ROOT / 'mlflow.db').as_posix()}"
)
mlflow.set_experiment("Visit_With_Us_Random_Forest")

with mlflow.start_run(run_name="github_actions_training"):

    search.fit(X_train, y_train)
    best_model = search.best_estimator_

    predictions = best_model.predict(X_test)
    probabilities = best_model.predict_proba(X_test)[:, 1]

    metrics = {
        "accuracy": accuracy_score(y_test, predictions),
        "precision": precision_score(
            y_test, predictions, zero_division=0
        ),
        "recall": recall_score(
            y_test, predictions, zero_division=0
        ),
        "f1_score": f1_score(
            y_test, predictions, zero_division=0
        ),
        "roc_auc": roc_auc_score(y_test, probabilities),
        "cv_roc_auc": search.best_score_,
    }

    mlflow.log_params({
        key.replace("classifier__", ""): value
        for key, value in search.best_params_.items()
    })
    mlflow.log_metrics(metrics)

    cv_results = pd.DataFrame(search.cv_results_)
    cv_results.to_csv(REPORT_DIR / "cv_results.csv", index=False)
    mlflow.log_artifact(str(REPORT_DIR / "cv_results.csv"))

    mlflow.sklearn.log_model(
        sk_model=best_model,
        name="random_forest_model",
        serialization_format="cloudpickle",
    )

    joblib.dump(best_model, MODEL_DIR / "best_model.joblib")

    with open(REPORT_DIR / "metrics.json", "w") as file:
        json.dump(metrics, file, indent=2)

    with open(REPORT_DIR / "best_params.json", "w") as file:
        json.dump(search.best_params_, file, indent=2)

    mlflow.log_artifact(str(REPORT_DIR / "metrics.json"))
    mlflow.log_artifact(str(REPORT_DIR / "best_params.json"))

print("Training completed successfully.")
print("Best parameters:", search.best_params_)
print("Evaluation metrics:", metrics)
print("Model saved:", MODEL_DIR / "best_model.joblib")
